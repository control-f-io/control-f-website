def page(template, job, jobs, edition, name):
    where = ("design-system/patterns/%s" if edition == "de"
             else "design-system/patterns/en/%s") % SPECIMEN
    doc = template
    for region, body in (
            ("head", lambda pad: head(job, edition, pad)),
            ("ld", lambda pad: ld(job, edition, pad)),
            ("crumb", lambda pad: '%s<span class="cf-breadcrumb__current" '
                                  'aria-current="page">%s</span>'
                                  % (pad, JOBS.title_html(job, edition))),
            ("title", lambda pad: '%s<h1 class="cf-page-header__title">%s</h1>'
                                  % (pad, JOBS.title_html(job, edition))),
            ("meta", lambda pad: meta(job, edition, pad)),
            ("task", lambda pad: task(job, edition, pad)),
            ("facts", lambda pad: facts(job, edition, pad)),
            ("prose", lambda pad: prose(job, edition, pad)),
            ("kennung", lambda pad: kennung(job, edition, pad)),
            ("more", lambda pad: more(job, jobs, edition, pad))):
        doc = splice(doc, region, body, where)

    doc = doc.replace(SPECIMEN, name)
    if not doc.startswith(DOCTYPE):
        fail("%s does not begin with a doctype" % where)
    rest = doc[len(DOCTYPE):]
    if rest.lstrip().startswith("<!-- GENERATED"):
        rest = rest[rest.index("-->") + 4:]
    return DOCTYPE + BANNER % (SPECIMEN, job["file"]) + rest


def build():
    jobs = JOBS.read_jobs()
    named = {}
    for j in jobs:
        name = JOBS.page_name(j)
        if name:
            named[name] = j
    out = {}
    for edition, home in (("de", PATTERNS), ("en", EN)):
        src = home / SPECIMEN
        if not src.exists():
            fail("no %s to build from.%s" % (src.relative_to(ROOT),
                 " Run python3 scripts/build-i18n.py first — the English "
                 "specimen is generated." if edition == "en" else ""))
        template = src.read_text(encoding="utf-8")
        for name, j in named.items():
            out[home / name] = page(template, j, jobs, edition, name)
    return out


def owned():
    return sorted(list(PATTERNS.glob("stelle-*.html")) + list(EN.glob("stelle-*.html")))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    pages = build()
    stale, missing, wrote = [], [], []
    for path, text in sorted(pages.items()):
        rel = path.relative_to(PATTERNS)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            if args.verbose:
                print("  ok       %s" % rel)
            continue
        if args.check:
            (missing if current is None else stale).append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            wrote.append(rel)

    # A page whose opening is gone. A filled position leaves content/jobs/, and
    # its page has to go with it — an advertisement the register stopped
    # listing and the site still serves is the worst of the three states.
    orphans = [p for p in owned() if p not in pages]
    for p in orphans:
        if args.check:
            print("  ORPHAN    %s — no opening in content/jobs/ writes it"
                  % p.relative_to(PATTERNS), file=sys.stderr)
        else:
            p.unlink()

    if args.check:
        if stale or missing or orphans:
            for r in missing:
                print("  MISSING   %s" % r, file=sys.stderr)
            for r in stale:
                print("  STALE     %s" % r, file=sys.stderr)
            print("\n%d job page(s) do not match content/jobs/.\n"
                  "    run: python3 scripts/build-stellen.py"
                  % (len(stale) + len(missing) + len(orphans)), file=sys.stderr)
            return 1
        print("stellen OK — %d page(s), %d opening(s) with an ad"
              % (len(pages), len(pages) // 2))
        return 0

    for r in wrote:
        print("  written  %s" % r)
    for p in orphans:
        print("  removed  %s" % p.relative_to(PATTERNS))
    print("stellen built — %d page(s) over both editions, %d changed"
          % (len(pages), len(wrote) + len(orphans)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
