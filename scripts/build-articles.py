def page(template, post, posts, edition, total, name):
    """One edition of one post: the specimen with nine regions replaced."""
    bs = post["text_de"] if edition == "de" else post["text_en"]
    where = ("design-system/patterns/%s" if edition == "de"
             else "design-system/patterns/en/%s") % SPECIMEN
    more = related(post, posts, edition, total, "    ")
    doc = template
    for region, body in (
            ("head", lambda pad: head(post, edition, pad)),
            ("crumb", lambda pad: crumb(post, edition, pad)),
            ("title", lambda pad: "%s<h1 class=\"cf-page-header__title\">%s</h1>"
                                  % (pad, esc(post["titel" if edition == "de" else "title"]))),
            ("meta", lambda pad: meta_line(post, edition, pad)),
            ("rail", lambda pad: rail(bs, edition, pad)),
            ("byline", lambda pad: byline(post, pad)),
            ("prose", lambda pad: prose(bs, edition, pad)),
            ("tail", lambda pad: tags(post, edition, pad)),
            ("related", lambda pad: related(post, posts, edition, total, pad))):
        doc = splice(doc, region, body, where)

    # THE FOOTER FOLLOWS THE LAST SECTION, in both directions.
    # `cf-footer--detached` is the footer's own gap, and it exists because the
    # section above it is `--flush` and brings none. The first article published
    # has no siblings to read on to, so Weiterlesen is not drawn, and the last
    # thing above the footer is the article body — which brings its own gap.
    # Left detached over it the air doubles, which is the finding
    # scripts/check-footer-parity.py raises as DETACHED and which was drawn
    # exactly that way before this. It comes back the moment a second post is
    # published, without anything here changing.
    if not more:
        doc, n = re.subn(r'(<footer class="cf-footer) cf-footer--detached"', r'\1"', doc)
        if n != 1:
            fail("%s: expected one detached footer to un-detach, found %d" % (name, n))

    # AN EMPTY BYLINE IS NOT AN EMPTY BOX. `.cf-article__byline` carries a
    # bottom rule and the air under it; with no author inside, what is drawn is
    # a hairline hanging over the text with nothing above it — read off the
    # rendered page, where it looks like a rule somebody meant. The whole box
    # goes, and the prose keeps the section's own spacing.
    if not byline(post, ""):
        doc, n = re.subn(
            r"[ \t]*<div class=\"cf-article__byline\">\s*"
            + re.escape(FENCE % "byline") + r"\s*"
            + re.escape(FENCE_END % "byline") + r"\s*</div>\n", "", doc)
        if n != 1:
            fail("%s: expected one empty byline box to remove, found %d" % (name, n))

    # THE SPECIMEN'S OWN NAME, everywhere it points at itself: the two
    # hreflang alternates, the language switch in the nav, and — on the English
    # page — the `../` back to the German edition. Replaced as a string rather
    # than matched attribute by attribute, because every one of them is the
    # same filename and a page that keeps one of them points a crawler at a
    # different article than the one it is on.
    doc = doc.replace(SPECIMEN, name)

    # The banner. On the English side there is one already — build-i18n.py's,
    # naming the specimen as the source — and it is replaced rather than added
    # to: two GENERATED notices disagreeing about what generated the file is
    # worse than none.
    if not doc.startswith(DOCTYPE):
        fail("%s does not begin with a doctype" % where)
        return
    rest = doc[len(DOCTYPE):]
    if rest.lstrip().startswith("<!-- GENERATED"):
        rest = rest[rest.index("-->") + 4:]
    return DOCTYPE + BANNER % (SPECIMEN, post["file"]) + rest


def build():
    """Both editions of every post that has a page. Returns {path: text}."""
    news = store()
    posts = news.read_posts()
    for p in posts:
        p["_news"] = news
    total = len(posts)

    named = {}
    for p in posts:
        name = news.page_name(p)
        if not name:
            continue
        if name in named:
            fail("two posts write the same page, %s — %s and %s. Two headlines "
                 "that reduce to the same name do this; change one of them."
                 % (name, named[name]["file"], p["file"]))
        named[name] = p

    out = {}
    for edition, home in (("de", PATTERNS), ("en", EN)):
        src = home / SPECIMEN
        if not src.exists():
            fail("no %s to build from.%s" % (src.relative_to(ROOT),
                 " Run python3 scripts/build-i18n.py first — the English "
                 "specimen is generated." if edition == "en" else ""))
        template = src.read_text(encoding="utf-8")
        for name, p in named.items():
            out[home / name] = page(template, p, posts, edition, total, name)
    return out


def owned():
    """Every article page on disk, in both editions."""
    return sorted(list(PATTERNS.glob("beitrag-*.html")) + list(EN.glob("beitrag-*.html")))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="fail if a page is stale, missing or orphaned")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    pages = build()
    stale, missing, wrote = [], [], []
    for path, text in sorted(pages.items()):
        rel = path.relative_to(PATTERNS)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            if args.verbose:
                print("  ok       %s" % rel)
            continue
        if args.check:
            (missing if current is None else stale).append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            wrote.append(rel)

    # A PAGE WHOSE POST IS GONE. Unpublishing in Notion removes the file from
    # content/news/, and the page has to go with it or the archive stops
    # listing an article the site still serves at its own address.
    orphans = [p for p in owned() if p not in pages]
    for p in orphans:
        if args.check:
            print("  ORPHAN    %s — no post in content/news/ writes it"
                  % p.relative_to(PATTERNS), file=sys.stderr)
        else:
            p.unlink()

    if args.check:
        if stale or missing or orphans:
            for r in missing:
                print("  MISSING   %s" % r, file=sys.stderr)
            for r in stale:
                print("  STALE     %s" % r, file=sys.stderr)
            print("\n%d article page(s) do not match content/news/.\n"
                  "    run: python3 scripts/build-articles.py"
                  % (len(stale) + len(missing) + len(orphans)), file=sys.stderr)
            return 1
        print("articles OK — %d page(s), %d post(s) with text"
              % (len(pages), len(pages) // 2))
        return 0

    for r in wrote:
        print("  written  %s" % r)
    for p in orphans:
        print("  removed  %s" % p.relative_to(PATTERNS))
    print("articles built — %d page(s) over both editions, %d changed"
          % (len(pages), len(wrote) + len(orphans)))
    if wrote or orphans:
        print("     then: python3 scripts/build-site.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
