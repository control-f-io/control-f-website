#!/usr/bin/env python3
"""One reading page per post, generated from content/news/ and the specimen.

WHAT WAS WRONG. Every card in the archive linked to blog-artikel.html. Eighteen
headlines, one destination: click "Wärmepumpen im Winter" and read about digital
twins. The card said one thing and the page said another — the same fault
build-news.py was written for one level up, where three counters claimed a
hundred and seventy-one articles that did not exist, and it is worse here
because the reader has already committed a click to it.

SO A POST WITH TEXT IS A PAGE. content/news/ holds one file per post; a post
that carries text carries it in both languages, divided by a line; and this
script writes `beitrag-<name>.html` for each of them, in German beside the
patterns and in English under patterns/en/. build-news.py links the card to the
page it knows this script will write — page_name() is defined once, there, and
read here, so the two cannot disagree about which posts have a page.

A POST WITHOUT TEXT GETS NO PAGE, and that is not an omission. The archive was
seeded from the cards of the mock-up: eighteen entries that are a headline, a
date and a reading time, with nothing written behind them. A generated page for
one of those would state "6 Min. Lesezeit" over an apology, which is the
original fault with an extra step. Their cards stay in the archive and stay
listings — build-news.py draws them as a <span> — and the moment somebody
writes the text, in Notion or in the file, the card becomes a link and this
script writes the page. Nothing else has to change.

THE FURNITURE IS NOT COPIED, IT IS READ. blog-artikel.html is the specimen of
the reading surface and it is written by hand, with figures, a plot, a table
and a pull quote that the markdown a post is written in cannot express. This
script reads that file and replaces the nine regions fenced by `article:…`
comments — the title, the byline, the text, the contents rail, what follows.
Everything outside those fences comes through untouched: the head, the consent
banner, the navigation, the article grid, the footer. A change to the reading
surface is made once, on the specimen, and every published article has it on
the next build.

AND THE ENGLISH EDITION IS THE SAME SPLICE ON THE TRANSLATED SPECIMEN.
build-i18n.py has already turned blog-artikel.html into en/blog-artikel.html —
the nav, the consent text and the footer are translated there, once, for
sixteen pages — and HTML comments are the one thing it never touches, so the
fences survive into the English file and mark the same nine regions. The
English page is that file with the post's English text spliced in. No article
sentence ever enters design-system/i18n/en.json: a catalogue is for the copy
that repeats across pages, and an article's text appears exactly once. Which is
also why this runs AFTER build-i18n.py — it needs the translated specimen —
and why build-i18n.py skips `beitrag-*.html`: those pages are already in both
languages before it looks at them.

    python3 scripts/build-articles.py           # write the article pages
    python3 scripts/build-articles.py --check   # fail if any is stale or orphaned
    python3 scripts/build-articles.py -v        # name every page, not only the new ones

stdlib only, no build step, no dependency. Same python3 that serves the pages.
"""

import argparse
import importlib.util
import pathlib
import re
import sys
import textwrap
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
PATTERNS = ROOT / "design-system" / "patterns"
EN = PATTERNS / "en"
SPECIMEN = "blog-artikel.html"

BANNER = (
    "<!-- GENERATED — DO NOT EDIT THIS FILE.\n"
    "     One post of the news archive, on the reading surface of\n"
    "     design-system/patterns/%s. The text is content/news/%s;\n"
    "     everything around it is that page. Change the post or the specimen,\n"
    "     then run:\n"
    "\n"
    "         python3 scripts/build-articles.py\n"
    "\n"
    "     CI runs `--check`, so an edit made here is lost rather than shipped. -->\n"
)

DOCTYPE = "<!DOCTYPE html>\n"

# The two words that name what kind of page this is, in the two editions. The
# specimen says "Analyse"/"Analysis" because it is one; a post does not declare
# a genre, and inventing one per post would be metadata written by a generator
# and read as a claim by a reader.
KIND = {"de": "Beitrag", "en": "Post"}
READ = {"de": "%s Min. Lesezeit", "en": "%s min read"}
CONTENTS = {"de": "Inhalt", "en": "Contents"}
MORE = {"de": "%d von %d", "en": "%d of %d"}

# WHO WROTE IT. The archive carries an author's name and nothing else, and this
# is where that name gets the job title ueber-uns.html shows for the same
# person. They are English titles on both editions, which is how that page
# already carries them, and lang="en" is what says so. A name that is not here
# still gets its byline — it gets the name alone, which is what the record has.
ROLE = {
    "Simon Deussen":     "Founder &amp; Managing Partner",
    "Daniel Tremer":     "Managing Partner",
    "Piet Brömmel":      "Data Engineer",
    "Henry Beiker":      "Data Engineer",
    "Robin Marzucca":    "Data Engineer",
    "Marie Ernø-Møller": "Data Engineer",
    "Birk Burghardt":    "Data Engineer",
}

# AND NO PHOTOGRAPH, WHICH IS DELIBERATE AND IS NOT PERMANENT. The byline box is
# a fixed 3rem, so scripts/check-image-scale.py holds whatever goes in it to a
# file between 96 and 144 device pixels — the 640 x 800 studio portraits are 4.4 x
# over that ceiling and are the fault that check was written for. The only files
# inside the window are portrait-01…04-144.jpg, and they are from the placeholder
# era: portrait-01 is not the person in simon.jpg and portrait-02 is not the
# person in daniel.jpg, compared side by side. There is no 144 px derivative
# filed under a person's name, and a byline is the one place a face is a claim
# about who wrote something. So a generated byline is a name and a role until
# those derivatives exist, at which point one line here gives every article a
# face. (blog-artikel.html still carries portrait-02-144.jpg under Daniel
# Tremer's name — that is the specimen's own stale claim, and it is not this
# script's to fix in passing.)


def fail(msg):
    print("build-articles: " + msg, file=sys.stderr)
    sys.exit(1)


IMG = ROOT / "design-system" / "assets" / "img"


def intrinsic(path):
    """A raster file's real pixel size, read from its header.

    scripts/check-image-scale.py owns this — "no decoder, no dependency" — and
    it is imported rather than written again because that file is also the one
    that FAILS on a width/height attribute which disagrees with the file. Two
    readers of a JPEG header would disagree about a progressive scan exactly
    once, and the check would be right and the page would be wrong.
    """
    spec = importlib.util.spec_from_file_location(
        "cf_image_scale", pathlib.Path(__file__).with_name("check-image-scale.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.intrinsic(str(path))


def store():
    """build-news.py, imported rather than copied.

    It owns content/news/ — the fields, the two-language body, the page name a
    post's card links to. A second reader of the same files would be a second
    opinion about what a post is, and the first thing the two would disagree
    about is which posts have a page at all.
    """
    spec = importlib.util.spec_from_file_location(
        "cf_build_news", pathlib.Path(__file__).with_name("build-news.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


