FENCE = "<!-- article:%s -->"
FENCE_END = "<!-- /article:%s -->"


def splice(html, name, body, where):
    """Replace one fenced region, keeping the fences and their indentation.

    An empty body leaves the fences with nothing between them — which is what a
    post with no author, no topics or no siblings has to produce. The fences
    stay because they are what the next build reads.
    """
    start, end = FENCE % name, FENCE_END % name
    m = re.search(re.escape(start) + r".*?" + re.escape(end), html, re.S)
    if not m:
        fail("%s has no %s … %s region. The fences are how this script knows "
             "what belongs to the post and what belongs to the page."
             % (where, start, end))
    pad = re.match(r"[ \t]*", html[html.rfind("\n", 0, m.start()) + 1:m.start()]).group(0)
    text = body(pad) if callable(body) else body
    inner = "\n%s\n%s" % (text, pad) if text else "\n%s" % pad
    return html[:m.start()] + start + inner + end + html[m.end():]


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def inline(s):
    """The three inline forms an editor produces: a link, bold, code.

    Escaped first and marked up after, so a `&` in a URL is an entity and a
    `<` in the text is not a tag. Nothing here is a general markdown parser —
    it is the set of things Notion's rich text can carry into a paragraph.
    """
    out = esc(s)
    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', out)
    out = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"`(.+?)`", r"<code>\1</code>", out)
    return out


def anchor(text):
    """A heading's id, and the fragment the contents rail links to.

    Built from the heading itself so the URL a reader copies out of the address
    bar says where they were. Each edition builds its own from its own heading:
    the German page's #datenfundament is #the-data-foundation on the English
    one, and a fragment in a language the page is not written in is a string
    nobody can check by looking.
    """
    s = text.lower()
    for a, b in (("ä", "ae"), ("ö", "oe"), ("ü", "ue"), ("ß", "ss")):
        s = s.replace(a, b)
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    s = re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", s)).strip("-")
    # Cut on a word. A fragment is read by people — it is what a shared link
    # ends in — and `#cop-ist-eine-momentaufnahme-jaz-ist-die-` is a heading
    # stopped mid-sentence with a hyphen hanging off it.
    if len(s) > 40:
        s = s[:40].rsplit("-", 1)[0]
    return s.strip("-")


def wrap(pad, opening, text, closing):
    """One block, set the way the specimen sets its paragraphs: the tags on
    their own lines and the text wrapped under them. A generated page is read
    in the repository as often as in a browser, and a paragraph on one 700
    character line is a diff nobody can review."""
    body = textwrap.fill(text, width=96 - len(pad),
                         initial_indent=pad + "  ", subsequent_indent=pad + "  ",
                         break_long_words=False, break_on_hyphens=False)
    return "%s%s\n%s\n%s%s" % (pad, opening, body, pad, closing)


def prose(bs, edition, pad):
    """The post's text, as the elements .cf-prose styles by name.

    The first block is the lead — set larger, and the paragraph the archive and
    the search results quote — which is why bodies() in build-news.py refuses a
    post that opens with a heading.
    """
    out = []
    for i, (kind, payload) in enumerate(bs):
        if kind == "p":
            cls = ' class="cf-article__lead"' if i == 0 else ""
            out.append(wrap(pad, "<p%s>" % cls, inline(payload), "</p>"))
        elif kind in ("h2", "h3"):
            out.append('%s<%s id="%s">%s</%s>'
                       % (pad, kind, anchor(payload), inline(payload), kind))
        elif kind == "img":
            out.append(picture(payload[0], payload[1], edition, pad))
        else:
            tag = "ul" if kind == "ul" else "ol"
            out.append("%s<%s>" % (pad, tag))
            for item in payload:
                out.append(wrap(pad + "  ", "<li>", inline(item), "</li>"))
            out.append("%s</%s>" % (pad, tag))
    return "\n".join(out)


def picture(path, caption, edition, pad):
    """One photograph, as a plate: `.cf-prose > figure` runs the full width.

    THREE THINGS ARE WRITTEN AND NONE OF THEM IS A CHOICE MADE HERE.

    `width` and `height` are the file's real pixel dimensions, read from its
    header. They are the aspect-ratio box the browser reserves before the bytes
    arrive — an article without them reflows under the reader's eye as each
    picture lands — and scripts/check-image-scale.py fails on a pair that
    disagrees with the file, which is what makes them worth writing at all.

    `alt` is empty because the caption is right underneath and says what the
    picture is. That is the W3C figure pattern, it is what
    scripts/check-a11y.py means by "write alt="" if it is decorative", and it
    is why build-news.py refuses a picture with no caption: the alternative is
    a screen reader reading the same sentence twice, or reading nothing.

    `loading="lazy"` because a picture below the fold in a piece somebody has
    not started reading is not worth a request yet — every other image on the
    site that is not the hero carries it for the same reason.

    AND THE PATH IS WRITTEN FOR THE EDITION IT IS ON. Every other asset
    reference on an English page got its second `../` from build-i18n.py, which
    never sees this markup: the English article is this text spliced into the
    already-translated specimen. Written with one `../` it resolved to nothing
    from patterns/en/, and build-site.py stopped the build for it — "a
    preview-only reference survived the edits" — which is the check doing its
    job on a path this file had to write itself.
    """
    up = "../../assets/img/" if edition == "en" else "../assets/img/"
    f = IMG / path
    if not f.exists():
        fail("%s does not exist. A post's picture is a file in the repository, "
             "downloaded from Notion by scripts/sync-news-notion.py — a page "
             "cannot link to one that is not there." % f.relative_to(ROOT))
    dims = intrinsic(f)
    if not dims:
        fail("%s: cannot read the pixel size out of this file's header. JPEG, "
             "PNG, WebP and GIF are what scripts/check-image-scale.py reads."
             % f.relative_to(ROOT))
    w, h = dims
    return ("%s<figure>\n"
            '%s  <img src="%s%s" alt="" width="%d" height="%d"\n'
            '%s       loading="lazy" decoding="async">\n'
            "%s\n"
            "%s</figure>"
            % (pad, pad, up, path, w, h, pad,
               wrap(pad + "  ", "<figcaption>", inline(caption), "</figcaption>"),
               pad))


def rail(bs, edition, pad):
    """The contents, from the piece's own h2s.

    Nothing at all when the piece has none. A rail listing one entry is a
    control that answers a question nobody asked, and an empty <ol> is a
    landmark a screen reader announces and then has nothing to read out.
    """
    heads = [p for k, p in bs if k == "h2"]
    if len(heads) < 2:
        return ""
    out = ['%s<nav aria-labelledby="inhaltsverzeichnis">' % pad,
           '%s  <p class="cf-article__toc-title" id="inhaltsverzeichnis">%s</p>'
           % (pad, CONTENTS[edition]),
           '%s  <ol class="cf-article__toc">' % pad]
    out += ['%s    <li><a href="#%s">%s</a></li>' % (pad, anchor(h), inline(h))
            for h in heads]
    out += ["%s  </ol>" % pad, "%s</nav>" % pad]
    return "\n".join(out)


def byline(post, pad):
    """The author, with the role ueber-uns.html carries for them.

    Nothing at all when the post names no author — an empty byline box above
    the text is a hole where a person should be.
    """
    who = post.get("autor")
    if not who:
        return ""
    out = ["%s<div>" % pad,
           '%s  <p class="cf-person__name">%s</p>' % (pad, esc(who))]
    if who in ROLE:
        out.append('%s  <p class="cf-person__role" lang="en">%s</p>' % (pad, ROLE[who]))
    out.append("%s</div>" % pad)
    return "\n".join(out)


def meta_line(post, edition, pad):
    """`Beitrag · 01.01.2026` and the reading time, the specimen's two spans.

    The date is written the way the edition's own archive writes it — dotted in
    German, `01 Jan 2026` in English — because the reader has just come from a
    card that said one of those two things.
    """
    news = post["_news"]
    shown = news.german(post["datum"]) if edition == "de" else news.en_meta(post["datum"])
    out = ['%s<span>%s · <time datetime="%s">%s</time></span>'
           % (pad, KIND[edition], post["datum"], shown)]
    if post.get("minuten"):
        out.append("%s<span>%s</span>" % (pad, READ[edition] % post["minuten"]))
    return "\n".join(out)


def head(post, edition, pad):
    """The title a tab shows and the description a result page quotes.

    The description is the lead's first sentences rather than a field of its
    own: a summary written separately is a summary that stops matching the
    piece, and every post already opens with the paragraph that says what it
    is about.
    """
    title = post["titel"] if edition == "de" else post["title"]
    lead = (post["text_de"] if edition == "de" else post["text_en"])[0][1]
    desc = summary(lead)
    return ('%s<title>%s — Control-F</title>\n'
            '%s<meta name="description" content="%s">'
            % (pad, esc(title), pad, esc(desc).replace('"', "&quot;")))


def summary(lead, limit=165):
    """The lead, cut to what a search result shows, on a sentence if it can be.

    Cut on a word at worst. A description that ends mid-word is the one part of
    a page a reader meets before they have decided to read it.
    """
    text = re.sub(r"\s+", " ", re.sub(r"[*`]|\[|\]\([^)]*\)", "", lead)).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit]
    stop = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
    if stop > limit * 0.5:
        return cut[:stop + 1]
    return cut[:cut.rfind(" ")].rstrip(",;:—-") + " …"


def crumb(post, edition, pad):
    """The breadcrumb's last step: the title without its subtitle.

    The specimen shortens "Digitale Zwillinge im Energiesektor: Simulation
    trifft Realität" to what stands before the colon, and that is the rule —
    a breadcrumb is a place, and the second half of a headline is an argument.
    """
    title = post["titel"] if edition == "de" else post["title"]
    short = title.split(":")[0].strip() if ":" in title else title
    if len(short) > 60:
        short = short[:57].rsplit(" ", 1)[0] + " …"
    return ('%s<span class="cf-breadcrumb__current" aria-current="page">%s</span>'
            % (pad, esc(short)))


def tags(post, edition, pad):
    """The post's topics, each a link into the archive filtered to it.

    THE WAY BACK OUT OF ONE ARTICLE IS THE ARCHIVE NARROWED TO ITS SUBJECT, and
    it is the reason the topics are on the post at all. The specimen has always
    drawn three of these chips under the text; every generated page drew none,
    because a post carried no topic to draw — the region was spliced empty and
    the reader who had just finished a piece about heat pumps was offered
    "Alle Beiträge" and nothing else.

    They point at news-thema-<slug>.html, which is where the chips on the
    archive point too. Not at a query string: the specimen said
    `news.html?thema=telemetrie` and no server answers that — the site is static
    files, and the link came back with the whole unfiltered archive.

    In the order the post writes them, which is the writer's order of
    importance. The archive's own chips are in the vocabulary's order instead;
    the two are different lists doing different jobs.
    """
    news = post["_news"]
    out = ['%s<ul class="cf-article__tags">' % pad]
    for slug, de, en, _prose in post["topics"]:
        out.append('%s  <li><a class="cf-article__tag" href="%s">%s</a></li>'
                   % (pad, news.thema_name(slug), esc(de if edition == "de" else en)))
    out.append("%s</ul>" % pad)
    return "\n".join(out)


def related(post, posts, edition, total, pad):
    """Up to three other posts that have a page, newest first.

    Only posts with a page. The section is called Weiterlesen and a card in it
    that leads nowhere is the fault this script exists to remove, drawn in the
    one place a reader has already agreed to keep reading.
    """
    news = post["_news"]
    others = [p for p in posts
              if p["file"] != post["file"] and news.page_name(p)][:3]
    if not others:
        return ""
    p2 = pad + "  "
    out = ['%s<section class="section section--flush" aria-labelledby="weiterlesen">' % pad,
           '%s<div class="container">' % p2,
           '%s  <div class="cf-section-header cf-section-header--flush">' % p2,
           '%s    <h2 class="cf-section-header__label" id="weiterlesen">%s</h2>'
           % (p2, "Weiterlesen" if edition == "de" else "Read on"),
           '%s    <span class="cf-section-header__count">%s</span>'
           % (p2, MORE[edition] % (len(others), total)),
           "%s  </div>" % p2,
           '%s  <div class="subdivide subdivide--even" style="--subdivide-count:%d">'
           % (p2, len(others)),
           '%s    <div class="cf-blog-grid subdivide__row">' % p2]
    for p in others:
        title = p["titel"] if edition == "de" else p["title"]
        date = news.german(p["datum"]) if edition == "de" else news.en_meta(p["datum"])
        line = date + (" · %s min" % p["minuten"] if p.get("minuten") else "")
        out += ['%s      <div class="cf-blog-col subdivide__col cf-blog-col--1">' % p2,
                '%s        <a class="cf-blog-card cf-blog-card--lead" href="%s">'
                % (p2, news.page_name(p)),
                '%s          <span class="cf-blog-card__title">%s</span>' % (p2, esc(title)),
                '%s          <span class="cf-blog-card__meta">%s</span>' % (p2, esc(line)),
                "%s        </a>" % p2,
                "%s      </div>" % p2]
    out += ["%s    </div>" % p2, "%s  </div>" % p2, "%s</div>" % p2, "%s</section>" % pad]
    return "\n".join(out)


